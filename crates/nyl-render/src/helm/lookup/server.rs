//! The in-process HTTPS server behind the lookup API.
//!
//! One server serves one Helm render. It binds a random port on 127.0.0.1,
//! presents a certificate generated for that render alone, and wants the
//! render's random bearer token. Helm reaches it through a temporary kubeconfig
//! that carries the certificate as its only trust anchor, so no other server and
//! no ambient credential can stand in for it. The server runs on its own thread
//! with its own runtime, because the render blocks on Helm.

use std::convert::Infallible;
use std::net::{SocketAddr, TcpListener};
use std::sync::Arc;
use std::thread::JoinHandle;

use base64::Engine as _;
use bytes::Bytes;
use http_body_util::Full;
use hyper::body::Incoming;
use hyper::service::service_fn;
use hyper::{Request, Response};
use hyper_util::rt::TokioIo;
use rustls::pki_types::{CertificateDer, PrivateKeyDer, PrivatePkcs8KeyDer};
use tokio::sync::oneshot;
use tokio_rustls::TlsAcceptor;

use super::api::{ApiState, Observation, RequestHead};
use super::model::StoreError;
use crate::{NylError, Result};

/// A started server, stopped when dropped.
pub struct ApiServer {
    address: SocketAddr,
    certificate_pem: String,
    token: String,
    state: Arc<ApiState>,
    shutdown: Option<oneshot::Sender<()>>,
    thread: Option<JoinHandle<()>>,
}

/// What a server did while it ran.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct ServerReport {
    /// The object requests it answered.
    pub observations: Vec<Observation>,
    /// The requests it failed with a 500.
    pub failures: Vec<StoreError>,
}

impl ApiServer {
    /// Start serving `state`. The token is generated by the caller, so tests and
    /// the kubeconfig agree on it.
    pub fn start(state: Arc<ApiState>, token: String) -> Result<Self> {
        let certified = rcgen::generate_simple_self_signed(vec!["127.0.0.1".to_owned()])
            .map_err(|error| NylError::process(format!("Failed to generate the lookup API certificate: {error}")))?;
        let certificate_pem = certified.cert.pem();
        let acceptor = tls_acceptor(certified.cert.der().to_vec(), certified.signing_key.serialize_der())?;

        let listener = TcpListener::bind(("127.0.0.1", 0))
            .map_err(|error| NylError::process(format!("Failed to bind the lookup API: {error}")))?;
        listener
            .set_nonblocking(true)
            .map_err(|error| NylError::process(format!("Failed to configure the lookup API: {error}")))?;
        let address = listener
            .local_addr()
            .map_err(|error| NylError::process(format!("Failed to read the lookup API address: {error}")))?;

        let (shutdown, stop) = oneshot::channel();
        let served = state.clone();
        let thread = std::thread::Builder::new()
            .name("nyl-lookup-api".to_owned())
            .spawn(move || {
                let runtime = match tokio::runtime::Builder::new_current_thread().enable_all().build() {
                    Ok(runtime) => runtime,
                    Err(error) => {
                        tracing::error!("Failed to start the lookup API runtime: {error}");
                        return;
                    }
                };
                runtime.block_on(serve(listener, acceptor, served, stop));
            })
            .map_err(|error| NylError::process(format!("Failed to start the lookup API: {error}")))?;
        Ok(Self {
            address,
            certificate_pem,
            token,
            state,
            shutdown: Some(shutdown),
            thread: Some(thread),
        })
    }

    pub fn address(&self) -> SocketAddr {
        self.address
    }

    /// The PEM of the certificate the server presents.
    pub fn certificate_pem(&self) -> &str {
        &self.certificate_pem
    }

    /// A kubeconfig whose only cluster is this server, trusting only its
    /// certificate, with the render's token as the only credential.
    pub fn kubeconfig(&self) -> String {
        let authority = base64::engine::general_purpose::STANDARD.encode(self.certificate_pem.as_bytes());
        format!(
            "apiVersion: v1\nkind: Config\nclusters:\n- name: nyl-lookup\n  cluster:\n    server: https://{}\n    certificate-authority-data: {authority}\nusers:\n- name: nyl-lookup\n  user:\n    token: {}\ncontexts:\n- name: nyl-lookup\n  context:\n    cluster: nyl-lookup\n    user: nyl-lookup\ncurrent-context: nyl-lookup\n",
            self.address, self.token
        )
    }

    /// Stop serving and report what the server answered.
    pub fn finish(mut self) -> ServerReport {
        self.stop();
        ServerReport {
            observations: self.state.observations(),
            failures: self.state.failures(),
        }
    }

    fn stop(&mut self) {
        if let Some(shutdown) = self.shutdown.take() {
            let _ = shutdown.send(());
        }
        if let Some(thread) = self.thread.take() {
            let _ = thread.join();
        }
    }
}

impl Drop for ApiServer {
    fn drop(&mut self) {
        self.stop();
    }
}

fn tls_acceptor(certificate: Vec<u8>, key: Vec<u8>) -> Result<TlsAcceptor> {
    let provider = Arc::new(rustls::crypto::aws_lc_rs::default_provider());
    let mut config = rustls::ServerConfig::builder_with_provider(provider)
        .with_safe_default_protocol_versions()
        .map_err(|error| NylError::process(format!("Failed to configure the lookup API TLS: {error}")))?
        .with_no_client_auth()
        .with_single_cert(
            vec![CertificateDer::from(certificate)],
            PrivateKeyDer::Pkcs8(PrivatePkcs8KeyDer::from(key)),
        )
        .map_err(|error| NylError::process(format!("Failed to configure the lookup API TLS: {error}")))?;
    config.alpn_protocols = vec![b"http/1.1".to_vec()];
    Ok(TlsAcceptor::from(Arc::new(config)))
}

async fn serve(listener: TcpListener, acceptor: TlsAcceptor, state: Arc<ApiState>, mut stop: oneshot::Receiver<()>) {
    let Ok(listener) = tokio::net::TcpListener::from_std(listener) else {
        tracing::error!("Failed to start the lookup API listener");
        return;
    };
    let mut connections = tokio::task::JoinSet::new();
    loop {
        tokio::select! {
            _ = &mut stop => break,
            accepted = listener.accept() => {
                let Ok((stream, _)) = accepted else { continue };
                let acceptor = acceptor.clone();
                let state = state.clone();
                connections.spawn(async move {
                    let Ok(stream) = acceptor.accept(stream).await else { return };
                    let service = service_fn(move |request| {
                        let state = state.clone();
                        async move { Ok::<_, Infallible>(handle(state, request).await) }
                    });
                    let _ = hyper::server::conn::http1::Builder::new()
                        .serve_connection(TokioIo::new(stream), service)
                        .await;
                });
            }
        }
    }
    connections.abort_all();
}

async fn handle(state: Arc<ApiState>, request: Request<Incoming>) -> Response<Full<Bytes>> {
    let method = request.method().as_str().to_owned();
    let path = request.uri().path().to_owned();
    let query = request.uri().query().map(ToOwned::to_owned);
    let header = |name: &str| {
        request
            .headers()
            .get(name)
            .and_then(|value| value.to_str().ok())
            .map(ToOwned::to_owned)
    };
    let (accept, authorization) = (header("accept"), header("authorization"));
    // Stores may block, so they never run on the server's own thread.
    let reply = tokio::task::spawn_blocking(move || {
        state.respond(&RequestHead {
            method: &method,
            path: &path,
            query: query.as_deref(),
            accept: accept.as_deref(),
            authorization: authorization.as_deref(),
        })
    })
    .await;
    let reply = reply
        .unwrap_or_else(|_| super::api::Reply::internal_error("the lookup API failed while answering the request"));
    let mut response = Response::builder()
        .status(reply.status)
        .header("Content-Type", reply.content_type)
        .header("Cache-Control", "no-store");
    if let Some(allow) = reply.allow {
        response = response.header("Allow", allow);
    }
    response
        .body(Full::new(Bytes::from(reply.body)))
        .unwrap_or_else(|_| Response::new(Full::new(Bytes::new())))
}

#[cfg(test)]
mod tests {
    use std::sync::Arc;

    use serde_json::json;

    use super::*;
    use crate::helm::lookup::api::ApiCapabilities;
    use crate::helm::lookup::model::ObjectSet;

    const TOKEN: &str = "render-token";

    fn server() -> ApiServer {
        let objects = ObjectSet::from_documents(
            vec![
                json!({"apiVersion": "v1", "kind": "ConfigMap", "metadata": {"name": "settings", "namespace": "demo"}}),
            ],
            &|_, _| Some(true),
            "demo",
        )
        .unwrap();
        let capabilities = ApiCapabilities::new("1.30.0", ["v1".to_owned()], []).unwrap();
        let state = Arc::new(ApiState::new(capabilities, Arc::new(objects), TOKEN.to_owned()));
        ApiServer::start(state, TOKEN.to_owned()).unwrap()
    }

    fn client(trusting: Option<&str>) -> reqwest::Client {
        let roots = trusting.map(|pem| reqwest::Certificate::from_pem(pem.as_bytes()).unwrap());
        reqwest::Client::builder()
            .tls_certs_only(roots)
            .no_proxy()
            .timeout(std::time::Duration::from_secs(10))
            .build()
            .unwrap()
    }

    #[tokio::test]
    async fn test_the_server_speaks_https_with_its_own_certificate_and_wants_the_token() {
        let server = server();
        let url = format!("https://{}", server.address());
        let trusting = client(Some(server.certificate_pem()));

        let found = trusting
            .get(format!("{url}/api/v1/namespaces/demo/configmaps/settings"))
            .bearer_auth(TOKEN)
            .send()
            .await
            .unwrap();
        assert_eq!(found.status(), 200);
        let body: serde_json::Value = serde_json::from_slice(&found.bytes().await.unwrap()).unwrap();
        assert_eq!(body["metadata"]["name"], "settings");

        let unauthenticated = trusting.get(format!("{url}/version")).send().await.unwrap();
        assert_eq!(unauthenticated.status(), 401);
        let write = trusting
            .post(format!("{url}/api/v1/namespaces/demo/configmaps"))
            .bearer_auth(TOKEN)
            .body("{}")
            .send()
            .await
            .unwrap();
        assert_eq!(write.status(), 405);

        // The certificate is the only trust anchor: another client cannot reach it.
        assert!(client(None)
            .get(format!("{url}/version"))
            .bearer_auth(TOKEN)
            .send()
            .await
            .is_err());
    }

    #[test]
    fn test_the_kubeconfig_names_only_this_server_and_its_certificate() {
        let server = server();
        let kubeconfig = server.kubeconfig();
        let document: serde_json::Value = serde_saphyr::from_str(&kubeconfig).unwrap();
        assert_eq!(document["clusters"].as_array().unwrap().len(), 1);
        assert_eq!(
            document["clusters"][0]["cluster"]["server"],
            format!("https://{}", server.address())
        );
        assert_eq!(document["users"][0]["user"]["token"], TOKEN);
        let authority = document["clusters"][0]["cluster"]["certificate-authority-data"]
            .as_str()
            .unwrap();
        assert_eq!(
            base64::engine::general_purpose::STANDARD.decode(authority).unwrap(),
            server.certificate_pem().as_bytes()
        );
    }

    #[test]
    fn test_finishing_reports_what_was_answered_and_stops_the_server() {
        let server = server();
        let address = server.address();
        let report = server.finish();
        assert_eq!(report, ServerReport::default());
        assert!(std::net::TcpStream::connect_timeout(&address, std::time::Duration::from_millis(500)).is_err());
    }
}
